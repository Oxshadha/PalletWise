"""First-time setup on any system (Windows, macOS, Linux), standard library only.

    python scripts/setup.py
    # or, without Python installed:
    docker run --rm -v "${PWD}:/w" -w /w python:3.13-alpine python scripts/setup.py

1. Creates .env from .env.example with fresh random secrets (an existing .env is kept).
2. Writes the demo account cards of the sign-in page for this installation
   (infra/keycloak/themes/palletwise/login/resources/js/demo-accounts.js, never committed).
"""

import base64
import json
import os
import secrets
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ENV, EXAMPLE = ROOT / ".env", ROOT / ".env.example"
DEMO = ROOT / "infra/keycloak/themes/palletwise/login/resources/js/demo-accounts.js"


def create_env() -> None:
    lines: list[str] = []
    for line in EXAMPLE.read_text(encoding="utf-8").splitlines():
        if line.startswith("#") and "change-me" in line:
            line = "# PalletWise local configuration, generated by scripts/setup.py with fresh secrets."
        elif line.startswith("PW_SESSION_KEYS="):
            line = "PW_SESSION_KEYS=k1:" + base64.b64encode(os.urandom(32)).decode()
        elif "=change-me" in line:
            line = line.replace("change-me", secrets.token_urlsafe(18))
        lines.append(line)
    ENV.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("Created .env with fresh secrets.")


def read_env() -> dict[str, str]:
    pairs = (line.split("=", 1) for line in ENV.read_text(encoding="utf-8").splitlines())
    return {k.strip(): v.strip() for k, *rest in pairs if rest for v in rest if not k.startswith("#")}


def write_demo_accounts(env: dict[str, str]) -> None:
    accounts = [
        {"role": "Warehouse manager", "username": "manager", "password": env.get("KC_DEV_MANAGER_PASSWORD")},
        {"role": "Admin", "username": "admin", "password": env.get("KC_DEV_ADMIN_PASSWORD")},
    ]
    DEMO.write_text(
        "// Demo accounts of this installation, written by scripts/setup.py. Never committed.\n"
        f"window.PW_DEMO_ACCOUNTS = {json.dumps(accounts, indent=2)};\n",
        encoding="utf-8",
    )
    print("Wrote the sign-in page's demo account cards.")


def main() -> None:
    if ENV.exists():
        print(".env exists; keeping it.")
    else:
        create_env()
    write_demo_accounts(read_env())
    print("Next: docker compose --env-file infra/images.env --env-file .env -f infra/compose.yaml")
    print("        up -d --build --wait   (or: make up)")
    print("Then open http://localhost:8080")


if __name__ == "__main__":
    main()
